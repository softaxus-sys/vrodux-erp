"""Builds src/lib/module-content.generated.ts from content/modules/*.md.

The markdown files are the source of truth for what each module page says. Anything under
"Do not claim yet" or "Verification status" is deliberately dropped so unbuilt features are
never published. Run:  python scripts/build-module-content.py
"""
import json, os, re

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
SRC = os.path.join(ROOT, "content", "modules")
OUT = os.path.join(ROOT, "src", "lib", "module-content.generated.ts")

# markdown file -> site slug
FILES = {
    "01-crm.md": "crm", "02-sales.md": "sales", "03-purchase.md": "purchase", "04-inventory.md": "inventory",
    "05-finance.md": "finance", "06-hr-payroll.md": "hr", "07-pos-retail.md": "pos", "08-restaurant.md": "restaurant",
    "09-hotel-pms.md": "hospitality", "10-tourism.md": "tourism", "11-real-estate.md": "real-estate",
    "12-project-management.md": "project-management", "13-visa-services.md": "visa-services",
    "14-manufacturing.md": "manufacturing", "15-library.md": "library", "16-import-export.md": "import-export",
    "17-lead-generation.md": "lead-generation", "19-ai-assistant.md": "ai-assistant", "20-platform.md": "platform",
}
DROP = ("do not claim yet", "verification status")


def sections(text):
    """Split into {heading_lower: [lines]} for ## sections plus the preamble."""
    out, cur, name = {}, [], "_pre"
    for line in text.splitlines():
        m = re.match(r"^##\s+(.*)", line)
        if m:
            out[name] = cur
            name, cur = m.group(1).strip().lower(), []
        else:
            cur.append(line)
    out[name] = cur
    return out


def para(lines):
    return " ".join(l.strip() for l in lines if l.strip()).strip()


def features(lines):
    groups, cur = [], None
    def new(title, desc=None):
        g = {"title": title, "items": []}
        if desc: g["items"].append(desc)
        groups.append(g)
        return g
    for raw in lines:
        l = raw.rstrip()
        if not l.strip():
            continue
        m = re.match(r"^\*\*(.+?)\*\*\s*(?:—|-|–)?\s*(.*)$", l)
        if m and not l.lstrip().startswith("-"):
            cur = new(m.group(1).strip().rstrip(":"), m.group(2).strip() or None)
        elif l.lstrip().startswith("- "):
            if cur is None:
                cur = new("What's included")
            cur["items"].append(l.lstrip()[2:].strip())
        else:
            if cur is None:
                cur = new("What's included")
            cur["items"].append(l.strip())
    return groups


def parse(text):
    pre_m = re.search(r"^#\s+(.*)", text, re.M)
    title = pre_m.group(1).strip() if pre_m else ""
    head = re.search(r"\*\*Headline:\*\*\s*(.*)", text)
    tag = re.search(r"\*\*Tagline:\*\*\s*(.*)", text)
    sec = sections(text)
    d = {"title": title, "headline": head.group(1).strip() if head else "", "tagline": tag.group(1).strip() if tag else ""}
    for key, name in (("overview", "overview"), ("who", "who it's for"), ("access", "access control"), ("worksWith", "works with"), ("needs", "needs")):
        if name in sec:
            d[key] = para(sec[name])
    for k, v in sec.items():
        if k.startswith("who it") and "who" not in d:
            d["who"] = para(v)
    if "features" in sec:
        d["groups"] = features(sec["features"])
    return d


def verticals(text):
    """18-industry-verticals.md: one '## Name' section per vertical (before 'Access control')."""
    sec = sections(text)
    mapping = {"b2b": "b2b-services", "education": "education", "healthcare": "healthcare", "insurance": "insurance"}
    out = {}
    for k, v in sec.items():
        if k in mapping:
            out[mapping[k]] = para(v)
    return out


def main():
    modules = {}
    for fn, slug in FILES.items():
        with open(os.path.join(SRC, fn), encoding="utf8") as f:
            modules[slug] = parse(f.read())
    with open(os.path.join(SRC, "18-industry-verticals.md"), encoding="utf8") as f:
        vt = verticals(f.read())
    for slug, summary in vt.items():
        modules[slug] = {"title": slug, "headline": "", "tagline": "", "summary": summary}
    ts = (
        "// GENERATED by scripts/build-module-content.py from content/modules/*.md. Do not edit by hand.\n"
        "export interface ModuleContentGroup { title: string; items: string[] }\n"
        "export interface ModuleContent {\n"
        "  title: string; headline: string; tagline: string; overview?: string; who?: string;\n"
        "  groups?: ModuleContentGroup[]; worksWith?: string; access?: string; needs?: string; summary?: string;\n"
        "}\n\n"
        "export const moduleContent: Record<string, ModuleContent> = " + json.dumps(modules, indent=2, ensure_ascii=False) + ";\n"
    )
    with open(OUT, "w", encoding="utf8", newline="\n") as f:
        f.write(ts)
    print("wrote", OUT, len(modules), "modules")


main()
