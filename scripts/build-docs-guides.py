"""Builds src/components/docs/docs-guides.generated.ts from content/docs/*.md.

Each markdown file holds one docs category. Layout:

    @@category slug | Name | Description | IconName      (only for NEW categories; optional)
    @@ article-slug | Title | One-line summary
    ...body in the docs markdown-lite format (## headings, - bullets, 1. steps, [text](/docs/..))...

Articles are numbered in file order, starting after the existing article(s) in that category.
Run:  python scripts/build-docs-guides.py
"""
import glob, json, os, re

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
SRC = os.path.join(ROOT, "content", "docs")
OUT = os.path.join(ROOT, "src", "components", "docs", "docs-guides.generated.ts")

# Existing hand-written article count per category (the generated ones follow them).
EXISTING = {"start-here": 7}


def words(s):
    return len(re.findall(r"\w+", s))


def main():
    cats, arts = [], []
    for path in sorted(glob.glob(os.path.join(SRC, "*.md"))):
        slug = os.path.splitext(os.path.basename(path))[0]
        slug = re.sub(r"^\d+-", "", slug)
        text = open(path, encoding="utf8").read().replace("\r\n", "\n")
        order = EXISTING.get(slug, 1)
        cur = None
        for line in text.split("\n"):
            m = re.match(r"^@@category\s+(.*)$", line)
            if m:
                parts = [p.strip() for p in m.group(1).split("|")]
                cats.append({"slug": parts[0], "name": parts[1], "description": parts[2], "icon": parts[3]})
                continue
            m = re.match(r"^@@\s*([a-z0-9-]+)\s*\|\s*(.*?)\s*\|\s*(.*)$", line)
            if m:
                if cur:
                    arts.append(cur)
                order += 1
                cur = {"slug": m.group(1), "categorySlug": slug, "title": m.group(2), "summary": m.group(3), "order": order, "body": []}
                continue
            if cur is not None:
                cur["body"].append(line)
        if cur:
            arts.append(cur)
    for a in arts:
        body = "\n".join(a["body"]).strip()
        a["body"] = "\n" + body + "\n"
        a["readTime"] = max(2, round(words(body) / 200))
        a["placeholder"] = False
    ts = (
        "// GENERATED by scripts/build-docs-guides.py from content/docs/*.md. Do not edit by hand.\n"
        "export interface GuideCategory { slug: string; name: string; description: string; icon: string }\n"
        "export interface GuideArticle { slug: string; categorySlug: string; title: string; summary: string; readTime: number; order: number; placeholder: boolean; body: string }\n\n"
        "export const guideCategories: GuideCategory[] = " + json.dumps(cats, indent=2, ensure_ascii=False) + ";\n\n"
        "export const guideArticles: GuideArticle[] = " + json.dumps(arts, indent=2, ensure_ascii=False) + ";\n"
    )
    open(OUT, "w", encoding="utf8", newline="\n").write(ts)
    print("categories:", len(cats), "articles:", len(arts))


main()
